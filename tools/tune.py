#!/usr/bin/env python3
"""Brute-force autotuner over every registered template instantiation.

    python3 tools/tune.py                 # tune sweep.py's shape set, write winners
    python3 tools/tune.py --quick         # sweep.py's QUICK shapes only
    python3 tools/tune.py --emit-header   # winners for this arch -> include/aegis/winners/sm_<arch>.h

Candidates are the impls in `bench_gemm --list` (the C++ registry) whose names
start with one of FAMILIES. Each runs with --check on every shape; failing
configs are reported and never win. All rows (cuBLAS included) are ingested
into the perf DB as one run, then `perfdb.py winners` writes the winners table.
Pause background training on this machine before running (CLAUDE.md rule 6).
"""
from __future__ import annotations

import argparse
import json
import socket
import sqlite3
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import sweep  # same directory: shapes, run_one, paths

ROOT = sweep.ROOT
FAMILIES = ("regblock_", "mma_", "mma_pipe_")
REPS = 20


def registered() -> list[str]:
    out = subprocess.check_output([str(sweep.BUILD / "bench_gemm"), "--list"], text=True)
    names = [json.loads(l)["impl"] for l in out.splitlines() if l.strip()]
    return [n for n in names if n.startswith(FAMILIES)]


def perfdb(*args: str) -> None:
    subprocess.run([sys.executable, str(ROOT / "tools/perfdb.py"), *args], check=True)


def tune(shapes) -> None:
    candidates = registered()
    host = socket.gethostname()
    sweep.RESULTS.mkdir(exist_ok=True)
    manifest = sweep.RESULTS / f"manifest-{host}.json"
    if not manifest.exists():
        manifest.write_text(subprocess.check_output([str(sweep.BUILD / "aegis_manifest")], text=True))

    out = sweep.RESULTS / f"tune-{host}-{time.strftime('%Y%m%d-%H%M%S')}.jsonl"
    print(f"{len(candidates)} candidates x {len(shapes)} shapes, {REPS} reps each", flush=True)
    table = []
    with out.open("w") as f:
        for (m, n, k) in shapes:
            rows = {}
            for impl in ["cublas", *candidates]:
                row = sweep.run_one(impl, m, n, k, sweep.IMPLS.get(impl, {}).get("reps", REPS))
                if row:
                    f.write(json.dumps(row) + "\n")
                    rows[impl] = row
            table.append(((m, n, k), rows))
            sys.stdout.flush()

    perfdb("ingest", str(out), "--manifest", str(manifest))
    perfdb("winners")
    print(f"\nresults: {out}\n")
    print_table(table)


def print_table(table) -> None:
    """Winner per shape from this run only, with the gap to the runner-up."""
    hdr = f"{'M':>5} {'N':>5} {'K':>5}  {'winner':<30} {'% cuBLAS':>9}  {'runner-up':<30} {'gap':>6}"
    print(hdr)
    print("-" * len(hdr))
    failed = set()
    for (m, n, k), rows in table:
        cb = rows.get("cublas")
        ok = sorted((r for i, r in rows.items() if i != "cublas" and r["pass"]),
                    key=lambda r: r["median_us"])
        failed |= {(i, (m, n, k)) for i, r in rows.items() if not r["pass"]}
        if not ok:
            print(f"{m:>5} {n:>5} {k:>5}  {'(no passing config)':<30}")
            continue
        w = ok[0]
        pct = f"{cb['median_us'] / w['median_us'] * 100:8.1f}%" if cb else f"{'-':>9}"
        if len(ok) > 1:
            ru = ok[1]
            gap = f"{(ru['median_us'] / w['median_us'] - 1) * 100:5.1f}%"
            ru_name = ru["impl"]
        else:
            gap, ru_name = f"{'-':>6}", "-"
        print(f"{m:>5} {n:>5} {k:>5}  {w['impl']:<30} {pct}  {ru_name:<30} {gap}")
    print("\n% cuBLAS: cuBLAS median / winner median (100% = parity). "
          "gap: how much slower the runner-up's median is than the winner's.")
    if failed:
        print(f"\n{len(failed)} correctness failures (excluded):")
        for impl, shape in sorted(failed):
            print(f"  {impl} {shape}")


def emit_header(db: Path, arch: int | None) -> None:
    if arch is None:
        manifest = sweep.RESULTS / f"manifest-{socket.gethostname()}.json"
        arch = json.loads(manifest.read_text())["sm_arch"]
    con = sqlite3.connect(db)
    rows = con.execute(
        "SELECT w.shape_bucket, k.impl, w.pct_of_cublas FROM winners w "
        "JOIN kernels k USING(kernel_id) WHERE w.sm_arch = ? AND w.op = 'gemm' "
        "AND w.dtype = 'f16f32f16'", (arch,)).fetchall()
    entries = []
    for bucket, impl, pct in rows:
        m, n, k = (int(x) for x in bucket.split("x"))
        entries.append((m, n, k, impl, pct))
    entries.sort(key=lambda e: (e[1], e[2], e[0]))

    path = ROOT / "include" / "aegis" / "winners" / f"sm_{arch}.h"
    path.parent.mkdir(parents=True, exist_ok=True)
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"// Generated by tools/tune.py --emit-header on {socket.gethostname()}, {when}.",
        "// Do not edit. Regenerate on the device after tuning.",
        f"// Tuned GEMM winners for sm_{arch}, read by aegis::matmul (src/matmul.cu).",
        "#pragma once",
        '#include "aegis/matmul.h"',
        "",
    ]
    if entries:
        lines.append(f"#define AEGIS_WINNERS_SM{arch} 1")
        lines.append(f"inline constexpr aegis::detail::Winner kWinners_sm{arch}[] = {{")
        for m, n, k, impl, pct in entries:
            note = f"  // {pct:.1f}% of cuBLAS" if pct is not None else ""
            lines.append(f'    {{{m}, {n}, {k}, "{impl}"}},{note}')
        lines.append("};")
    else:
        lines.append(f"// No winners in the perf DB for sm_{arch}; aegis::matmul uses cuBLAS.")
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} winners to {path.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true", help="sweep.py QUICK shapes only")
    ap.add_argument("--emit-header", action="store_true",
                    help="write include/aegis/winners/sm_<arch>.h from the perf DB; no tuning")
    ap.add_argument("--arch", type=int, help="with --emit-header (default: this device's manifest)")
    ap.add_argument("--db", type=Path, default=ROOT / "results" / "aegis_perf.db")
    args = ap.parse_args()

    if args.emit_header:
        emit_header(args.db, args.arch)
        return
    if not (sweep.BUILD / "bench_gemm").exists():
        sys.exit("build/bench_gemm not found; run cmake --build build first")
    tune(sweep.QUICK if args.quick else sweep.SQUARE + sweep.QWEN)


if __name__ == "__main__":
    main()
